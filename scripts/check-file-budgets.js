#!/usr/bin/env node
/**
 * File-size ratchet (QG-4).
 *
 * Eleven PHP files hold 47% of lib/ and ten .vue files 41% of src/. The point
 * of this guard is not to hit the target sizes today — ApiController is 3881
 * lines against a 600-line budget and no single commit is going to fix that.
 * The point is that those numbers may only ever go DOWN.
 *
 * How it works: .file-budgets.json records, per file, the line count at the
 * moment it was last lowered. A file over its recorded size fails the check. A
 * file under it also "fails", with a message telling you to run --update — that
 * is the ratchet clicking: the new, lower number gets written and can never be
 * exceeded again.
 *
 * The baseline is generated AFTER the F0 dead-code sweep on purpose. Recording
 * it first would have frozen 208 dead lines in PageService and 256 unreachable
 * ones in ExportService into the budget, making the guard certify code we were
 * about to delete.
 *
 * Targets (from the refactor plan, for orientation — not enforced yet):
 *   controller <= 600 . service <= 1200 . .vue <= 800
 *
 * A file may be listed in DELIBERATELY_LARGE when splitting it would cost more
 * than it saves. That does not relax the ratchet -- it still may not grow -- it
 * only stops it being counted as debt, so the "above target" number stays a
 * list of files someone should still shrink.
 *
 * Run standalone, via `npm run lint:budgets`, or `--update` to re-record.
 */

const { execFileSync } = require('child_process')
const fs = require('fs')
const path = require('path')

const REPO_ROOT = path.resolve(__dirname, '..')
const BUDGET_FILE = path.join(REPO_ROOT, '.file-budgets.json')

const TARGETS = [
	{ label: 'controller', target: 600, match: (f) => f.startsWith('lib/Controller/') && f.endsWith('.php') },
	{ label: 'service', target: 1200, match: (f) => f.startsWith('lib/Service/') && f.endsWith('.php') },
	{ label: 'vue', target: 800, match: (f) => f.startsWith('src/') && f.endsWith('.vue') },
]

/**
 * Files that are deliberately over target, with the reason.
 *
 * NOT an escape hatch for "we did not get round to it" — the ratchet already
 * handles that by letting a file sit above target while forbidding growth. This
 * is for the narrower case where splitting the file would COST something, and
 * the entry has to say what.
 *
 * An exempt file still may not grow: the ratchet applies exactly as before. All
 * this changes is that it stops being counted as debt in the summary line, so
 * "29 still above target" means 29 files someone should still shrink.
 */
const DELIBERATELY_LARGE = {
	'lib/Controller/PublicShareController.php':
		'The anonymous surface is this one file, by design (F6/F6d) and enforced by '
		+ 'PublicEndpointInventoryTest: a #[PublicPage] outside this namespace fails the '
		+ 'suite. Splitting it would answer "what can an anonymous visitor reach?" with '
		+ 'two files instead of one, and the four widget endpoints only account for 248 '
		+ 'lines -- not enough to reach the 600 target anyway. Shrink it by moving logic '
		+ 'into lib/Service/PublicShare/, as PR-B and PR-C did, not by splitting the class.',
}

function categoryOf(file) {
	return TARGETS.find((t) => t.match(file)) || null
}

function trackedFiles() {
	const out = execFileSync('git', ['ls-files', '-z'], { cwd: REPO_ROOT, maxBuffer: 32 * 1024 * 1024 })
	return out.toString('utf8').split('\0').filter(Boolean)
}

function lineCount(file) {
	const raw = fs.readFileSync(path.join(REPO_ROOT, file))
	if (raw.length === 0) return 0
	let n = 0
	for (let i = 0; i < raw.length; i++) if (raw[i] === 0x0a) n++
	if (raw[raw.length - 1] !== 0x0a) n++ // last line without trailing newline
	return n
}

function measure() {
	const sizes = {}
	for (const file of trackedFiles()) {
		if (!categoryOf(file)) continue
		if (!fs.existsSync(path.join(REPO_ROOT, file))) continue
		sizes[file] = lineCount(file)
	}
	return sizes
}

function loadBudgets() {
	if (!fs.existsSync(BUDGET_FILE)) return null
	return JSON.parse(fs.readFileSync(BUDGET_FILE, 'utf8'))
}

function writeBudgets(sizes) {
	const ordered = {}
	for (const key of Object.keys(sizes).sort()) ordered[key] = sizes[key]
	const payload = {
		_comment: 'Generated by scripts/check-file-budgets.js. Line counts may only decrease. Run `npm run lint:budgets -- --update` after shrinking a file.',
		_targets: Object.fromEntries(TARGETS.map((t) => [t.label, t.target])),
		files: ordered,
	}
	fs.writeFileSync(BUDGET_FILE, JSON.stringify(payload, null, 2) + '\n')
}

function main() {
	const update = process.argv.includes('--update')
	const sizes = measure()
	const budgets = loadBudgets()

	// A stale exemption is worse than none: it hides a file that has since been
	// brought under target, and nobody notices the note is obsolete.
	for (const file of Object.keys(DELIBERATELY_LARGE)) {
		if (sizes[file] === undefined) {
			console.error(`✗ ${file} is exempt in DELIBERATELY_LARGE but is not a tracked, measured file.`)
			process.exit(1)
		}
		const cat = categoryOf(file)
		if (sizes[file] <= cat.target) {
			console.error(`✗ ${file} is exempt in DELIBERATELY_LARGE but is now ${sizes[file]} lines, within the ${cat.target} target.`)
			console.error('  Remove the exemption -- it no longer describes anything.')
			process.exit(1)
		}
	}

	if (!budgets) {
		writeBudgets(sizes)
		console.log(`✓ Wrote initial budget baseline for ${Object.keys(sizes).length} files`)
		return
	}

	const recorded = budgets.files || {}
	const grew = []
	const shrank = []

	for (const [file, size] of Object.entries(sizes)) {
		const limit = recorded[file]
		if (limit === undefined) continue // new file: recorded on the next --update
		if (size > limit) grew.push({ file, size, limit })
		else if (size < limit) shrank.push({ file, size, limit })
	}

	const newFiles = Object.keys(sizes).filter((f) => recorded[f] === undefined)

	if (update) {
		writeBudgets(sizes)
		console.log(`✓ Budgets updated (${shrank.length} lowered, ${newFiles.length} newly recorded)`)
		return
	}

	if (grew.length > 0) {
		console.error('✗ File budget exceeded — these files grew:\n')
		for (const { file, size, limit } of grew.sort((a, b) => (b.size - b.limit) - (a.size - a.limit))) {
			const cat = categoryOf(file)
			console.error(`  ${file}`)
			console.error(`      ${limit} -> ${size} lines (+${size - limit}); ${cat.label} target is ${cat.target}`)
		}
		console.error('\nThese files are already over their target size. Extract code instead of adding to them.')
		console.error('If the growth is genuinely unavoidable, run: npm run lint:budgets -- --update')
		process.exit(1)
	}

	if (shrank.length > 0) {
		console.error('✗ Files shrank — the ratchet needs to click:\n')
		for (const { file, size, limit } of shrank) {
			console.error(`  ${file}: ${limit} -> ${size} lines (-${limit - size})`)
		}
		console.error('\nRun: npm run lint:budgets -- --update')
		process.exit(1)
	}

	if (newFiles.length > 0) {
		console.error(`✗ ${newFiles.length} new file(s) not yet in the baseline:\n`)
		for (const f of newFiles) console.error(`  ${f} (${sizes[f]} lines)`)
		console.error('\nRun: npm run lint:budgets -- --update')
		process.exit(1)
	}

	const over = Object.entries(sizes)
		.filter(([f, s]) => s > categoryOf(f).target && !DELIBERATELY_LARGE[f]).length
	const exempt = Object.keys(sizes).filter((f) => DELIBERATELY_LARGE[f]).length
	const note = exempt > 0 ? `, ${exempt} deliberately large` : ''
	console.log(`✓ File budgets: ${Object.keys(sizes).length} files, none grew (${over} still above target${note})`)
}

main()
